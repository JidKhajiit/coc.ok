export const LOCALES: Locale[] = ['ru', 'en']

export function normalizeLocale(value: unknown): Locale {
  return value === 'en' ? 'en' : 'ru'
}

export function localeTag(locale: Locale): string {
  return locale === 'en' ? 'en-US' : 'ru-RU'
}

